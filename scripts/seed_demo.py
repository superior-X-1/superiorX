def make_simple_pdf(title: str, text_lines: list) -> bytes:
    """Generates standard binary PDF 1.4 without external dependencies."""
    content = f"BT /F1 14 Tf 40 730 Td ({title}) Tj ET\n"
    content += "BT /F1 9 Tf 40 710 Td (GOVERNMENT OF BIHAR - DIRECTORATE OF LEGAL METROLOGY) Tj ET\n"
    content += "BT /F1 9 Tf 40 695 Td (Statutory Metrology Inspection & Stamping Record - OIML R76 Compliance) Tj ET\n"
    y = 665
    for line in text_lines:
        safe_line = line.replace("(", "[").replace(")", "]")
        content += f"BT /F1 10 Tf 40 {y} Td ({safe_line}) Tj ET\n"
        y -= 20
    content += f"BT /F1 9 Tf 40 100 Td (Generated by MeasureX Digital Metrology Platform - Section 24 Certified) Tj ET\n"
    
    stream_bytes = content.encode("latin1")
    stream_len = len(stream_bytes)
    
    pdf = f"""%PDF-1.4
1 0 obj <</Type /Catalog /Pages 2 0 R>> endobj
2 0 obj <</Type /Pages /Kids [3 0 R] /Count 1>> endobj
3 0 obj <</Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources <</Font <</F1 5 0 R>>>>>> endobj
4 0 obj <</Length {stream_len}>>
stream
{content}endstream
endobj
5 0 obj <</Type /Font /Subtype /Type1 /BaseFont /Helvetica>> endobj
xref
0 6
0000000000 65535 f 
0000000009 00000 n 
0000000056 00000 n 
0000000111 00000 n 
0000000212 00000 n 
0000000263 00000 n 
trailer <</Size 6 /Root 1 0 R>>
startxref
340
%%EOF"""
    return pdf.encode("latin1")


